// ---------------------------------------------------------------------------
// File-scope registry
//
// GetFrameDescriptorMap()  : returns reference to map of registered
//                            QCNodeFrameDescType_e to factory function.
// GetFrameDescriptorTypes(): returns reference to ordered list of registered
//                            types.
//
// Both containers are populated at static-initialisation time by the
// RegisterFD<ClassName> objects instantiated by REGISTER_FRAME_DESCRIPTOR()
// macros placed in each frame descriptor's translation unit.
//
// Using the "construct on first use" idiom to avoid static initialization
// order fiasco — mirrors the same pattern in QCNodeFactory.cpp.
// ---------------------------------------------------------------------------
static std::map<QCNodeFrameDescType_e, FrameDescriptor_CreateFunction_t> &GetFrameDescriptorMap()
{
    static std::map<QCNodeFrameDescType_e, FrameDescriptor_CreateFunction_t> s_map;
    return s_map;
}

static std::vector<QCNodeFrameDescType_e> &GetFrameDescriptorTypes()
{
    static std::vector<QCNodeFrameDescType_e> s_types;
    return s_types;
}

// ---------------------------------------------------------------------------
// RegisterFrameDescriptorCreator
//
// Free function declared in QCNodeFrameDescriptorFactory.hpp.
// Associates a QCNodeFrameDescType_e key with a FrameDescriptor_CreateFunction_t.
//
// Returns QC_STATUS_OK when the pair was inserted, or QC_STATUS_ALREADY when a
// creator was already registered for the same type.  The caller (the static
// initialiser generated by REGISTER_FRAME_DESCRIPTOR) stores this value, so the
// registration always runs and the result is never silently discarded.  A
// debug-build assertion still flags duplicate registrations as a programming
// error.
//
// ISO 26262:6 Table 8 §1a : single return statement at end of function.
// ---------------------------------------------------------------------------
QCStatus_e RegisterFrameDescriptorCreator( QCNodeFrameDescType_e type,
                                           FrameDescriptor_CreateFunction_t createFnc )
{
    QCStatus_e status = QC_STATUS_OK;

    auto &fdMap = GetFrameDescriptorMap();
    auto &fdTypes = GetFrameDescriptorTypes();

    auto it = fdMap.find( type );
    if ( it == fdMap.end() )
    {
        fdMap[type] = createFnc;
        fdTypes.push_back( type );
    }
    else
    {
        assert( 0 );   // duplicate registration for the same QCNodeFrameDescType_e
        status = QC_STATUS_ALREADY;
    }

    return status;
}

// ---------------------------------------------------------------------------
// CreateFrameDescriptor
//
// Looks up the registered factory function for the requested descriptor type
// and invokes it with numOfBuffers.  outDescriptor is reset to nullptr when:
//   - the type is not registered  (QC_STATUS_UNSUPPORTED)
//   - numOfBuffers is 0           (QC_STATUS_BAD_ARGUMENTS)
//   - allocation fails            (QC_STATUS_FAIL)
//
// ISO 26262:6 Table 8 §1a : single return statement at end of function.
// ISO 26262:6 Table 8 §1b : outDescriptor is null on error.
// ---------------------------------------------------------------------------
QCStatus_e QCNodeFrameDescriptorFactory::CreateFrameDescriptor(
        QCNodeFrameDescType_e type, uint32_t numOfBuffers,
        std::unique_ptr<QCFrameDescriptorNodeIfs> &outDescriptor )
{
    QCStatus_e status = QC_STATUS_OK;

    outDescriptor.reset();

    if ( numOfBuffers == 0U )
    {
        status = QC_STATUS_BAD_ARGUMENTS;
    }
    else
    {
        auto &fdMap = GetFrameDescriptorMap();
        auto it = fdMap.find( type );
        if ( it != fdMap.end() )
        {
            FrameDescriptor_CreateFunction_t createFnc = it->second;
            outDescriptor = createFnc( numOfBuffers );
            if ( !outDescriptor )
            {
                status = QC_STATUS_FAIL;
            }
        }
        else
        {
            status = QC_STATUS_UNSUPPORTED;
        }
    }

    return status;
}

// ---------------------------------------------------------------------------
// GetSupportedNodeFrameDescriptorTypes
//
// Returns the list of QCNodeFrameDescType_e values that have been registered
// via REGISTER_FRAME_DESCRIPTOR() in the current build.  The list is built
// incrementally by RegisterFrameDescriptorCreator() and reflects exactly
// the set of types for which CreateFrameDescriptor() will succeed.
// ---------------------------------------------------------------------------
QCStatus_e QCNodeFrameDescriptorFactory::GetSupportedNodeFrameDescriptorTypes(
        std::vector<QCNodeFrameDescType_e> &outTypes )
{
    outTypes = GetFrameDescriptorTypes();
    return QC_STATUS_OK;
}

